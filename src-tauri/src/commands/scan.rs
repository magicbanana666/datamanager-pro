//! Tauri commands for the Phase 3 recursive scanner.
//!
//! `start_scan` kicks off a real, cancellable scan on a background
//! task and returns immediately with a scan id - the scan itself can
//! run far longer than a single request/response round trip should,
//! so its progress and outcome are streamed back via events instead
//! of the command's own return value:
//!
//! - `scan-progress` - emitted roughly every 150ms while a scan runs.
//! - `scan-complete` - emitted once, carrying the full `ScanResult`.
//! - `scan-cancelled` - emitted once, instead of `scan-complete`, if
//!   `cancel_scan` was called before the scan finished.
//! - `scan-error` - emitted only if the scan task itself panics (a
//!   bug, not a normal outcome - every expected failure, like an
//!   unreadable subfolder, is recorded in `ScanResult.skipped`
//!   instead of aborting the scan).
//!
//! `cancel_scan` flips a shared, cooperatively-checked flag; the
//! running scan notices it on its own schedule (see
//! `services::scan_service` and `platform::current::try_mft_scan`) and
//! reports back via `scan-cancelled` rather than stopping instantly.

use crate::models::errors::{AppError, AppErrorCode};
use crate::models::scan::{ScanOptions, ScanProgress, ScanProgressState, ScanResult};
use crate::services::{path_service, scan_service};
use serde::Serialize;
use std::collections::HashMap;
use std::sync::atomic::Ordering;
use std::sync::{Arc, Mutex};
use std::time::{Duration, Instant};
use tauri::{AppHandle, Emitter, Manager};

/// Tracks every scan currently in flight, keyed by scan id, so
/// `cancel_scan` can find its cancellation flag and the progress
/// ticker can read its live counters. Entries are removed once a scan
/// finishes, however it finishes.
#[derive(Default)]
pub struct ScanRegistry {
    scans: Mutex<HashMap<String, Arc<ScanProgressState>>>,
}

const PROGRESS_INTERVAL: Duration = Duration::from_millis(150);

#[derive(Serialize)]
#[serde(rename_all = "camelCase")]
struct ScanCancelledPayload<'a> {
    scan_id: &'a str,
}

#[derive(Serialize)]
#[serde(rename_all = "camelCase")]
struct ScanErrorPayload<'a> {
    scan_id: &'a str,
    error: AppError,
}

/// Validates and normalizes `path`, registers the scan under
/// `scan_id`, and spawns it on a background task - returning as soon
/// as it's running, not once it's done. Rejects synchronously (no
/// event needed) if `path` plainly isn't a scannable folder.
///
/// `scan_id` is generated by the *caller* (the frontend), not here -
/// deliberately, so it can subscribe to that id's events before this
/// command's promise even resolves. Generating the id on this side and
/// returning it would leave a real race: a scan of a tiny folder can
/// finish before the frontend gets a chance to call `listen()` on an
/// id it didn't have yet.
#[tauri::command]
pub async fn start_scan(
    app: AppHandle,
    scan_id: String,
    path: String,
    options: ScanOptions,
) -> Result<(), AppError> {
    let validation = path_service::validate(&path);
    if !validation.exists || !validation.is_directory {
        return Err(validation.error.unwrap_or_else(|| {
            AppError::invalid_path(path.clone(), "The scan location is not a folder.")
        }));
    }
    let normalized = validation.normalized_path.unwrap_or(path);

    let state = Arc::new(ScanProgressState::new());
    app.state::<ScanRegistry>()
        .scans
        .lock()
        .unwrap()
        .insert(scan_id.clone(), state.clone());

    tracing::info!(scan_id = %scan_id, path = %normalized, "scan starting");
    tauri::async_runtime::spawn(run_and_report(app, scan_id, normalized, options, state));

    Ok(())
}

/// Flips the cancellation flag for `scan_id` if it's still running.
/// Not finding it is a no-op, not an error - the scan may have already
/// finished before the request arrived.
#[tauri::command]
pub fn cancel_scan(app: AppHandle, scan_id: String) -> Result<(), AppError> {
    if let Some(state) = app
        .state::<ScanRegistry>()
        .scans
        .lock()
        .unwrap()
        .get(&scan_id)
    {
        tracing::info!(scan_id = %scan_id, "scan cancellation requested");
        state.cancel();
    }
    Ok(())
}

fn emit_progress(app: &AppHandle, scan_id: &str, state: &ScanProgressState, started: Instant) {
    let progress = ScanProgress {
        scan_id: scan_id.to_string(),
        scanned_files: state.files.load(Ordering::Relaxed),
        scanned_folders: state.folders.load(Ordering::Relaxed),
        scanned_bytes: state.bytes.load(Ordering::Relaxed),
        current_path: state.current_path.lock().unwrap().clone(),
        elapsed_ms: started.elapsed().as_millis() as u64,
    };
    let _ = app.emit("scan-progress", &progress);
}

/// Runs the scan on a blocking task while a lightweight ticker emits
/// progress every [`PROGRESS_INTERVAL`], then emits exactly one of
/// `scan-complete` / `scan-cancelled` / `scan-error` and deregisters
/// the scan. Lives entirely in async-land (this function itself is
/// never blocking) so the ticker can run concurrently with the actual
/// scan work.
async fn run_and_report(
    app: AppHandle,
    scan_id: String,
    path: String,
    options: ScanOptions,
    state: Arc<ScanProgressState>,
) {
    let started = Instant::now();
    let blocking_state = state.clone();
    let mut handle = tokio::task::spawn_blocking(move || {
        scan_service::run_scan(&path, options, &blocking_state)
    });

    let mut ticker = tokio::time::interval(PROGRESS_INTERVAL);
    ticker.tick().await; // the first tick fires immediately - nothing to report yet

    let outcome = loop {
        tokio::select! {
            result = &mut handle => break result,
            _ = ticker.tick() => emit_progress(&app, &scan_id, &state, started),
        }
    };

    app.state::<ScanRegistry>()
        .scans
        .lock()
        .unwrap()
        .remove(&scan_id);
    let elapsed_ms = started.elapsed().as_millis() as u64;

    match outcome {
        Err(join_err) => {
            tracing::error!(error = %join_err, scan_id = %scan_id, "scan task panicked");
            let _ = app.emit(
                "scan-error",
                &ScanErrorPayload {
                    scan_id: &scan_id,
                    error: AppError::new(
                        AppErrorCode::Unknown,
                        "An unexpected internal error occurred during the scan.",
                    ),
                },
            );
        }
        Ok((_root, _engine)) if state.is_cancelled() => {
            tracing::info!(scan_id = %scan_id, "scan cancelled");
            let _ = app.emit(
                "scan-cancelled",
                &ScanCancelledPayload { scan_id: &scan_id },
            );
        }
        Ok((root, engine)) => {
            tracing::info!(
                scan_id = %scan_id,
                engine = ?engine,
                elapsed_ms,
                files = root.file_count,
                folders = root.folder_count,
                size = root.size,
                "scan complete"
            );
            let result = ScanResult {
                scan_id: scan_id.clone(),
                root,
                engine,
                elapsed_ms,
                skipped: state.take_skipped(),
            };
            let _ = app.emit("scan-complete", &result);
        }
    }
}
